    const github=new URL((await upstream.text()).match(/href="(https:\/\/github\.com[^"]+)"/)[1].replaceAll('&#38;','&'));
    const finish=await call('/callback?'+new URLSearchParams({state:github.searchParams.get('state'),code:'synthetic'}),{headers:{Cookie:cookie(upstream)}});
    assert.equal(finish.status,302);
    const tokens=await (await call('/token',{method:'POST',headers:{'Content-Type':'application/x-www-form-urlencoded'},body:new URLSearchParams({grant_type:'authorization_code',client_id:registered.client_id,code:new URL(finish.headers.get('Location')).searchParams.get('code'),redirect_uri:redirectUri,code_verifier:verifier,resource:base+'/mcp'}).toString()})).json();
    assert.ok(tokens.access_token);
    const mcp=message=>json('/mcp',message,{Authorization:'Bearer '+tokens.access_token});
    const ping={jsonrpc:'2.0',id:1,method:'ping'};
    assert.deepEqual(await (await mcp(ping)).json(),{jsonrpc:'2.0',id:1,result:{}});
