    assert.ok(status.result);assert.notEqual(status.result.isError,true);
    assert.equal((await mcp({jsonrpc:'2.0',id:3,method:'tools/call',params:{name:'jan_run_command',arguments:{command:'echo should-not-run'}}})).status,403);
    let dashboard=await (await call('/devices',{headers:{Cookie:ownerCookie}})).text();assert.match(dashboard,/data-selected="true"/);assert.match(dashboard,/data-presence>.*Online/);assert.match(dashboard,/Read only/);assert.match(dashboard,/Selected for AI tools/);
    socket.close();await pause(150);
    dashboard=await (await call('/devices',{headers:{Cookie:ownerCookie}})).text();assert.match(dashboard,/data-presence>.*Offline/);
    assert.equal((await mcp(ping)).status,503);
    socket=await connect();assert.equal((await mcp(ping)).status,200);
    assert.equal((await form('/devices/revoke',{id:approved.session.id,confirmation:'revoke'})).status,303);
    assert.equal((await call('/jan-relay/connect',{headers:{Upgrade:'websocket','X-JAN-Device-Proof':JSON.stringify(handshake(approved.session,key.privateKey))}})).status,403);
    assert.equal((await mcp(ping)).status,503);
    // Independently approve a control-capable device. The prior read-only
    // identity stays revoked; neither selection nor OAuth can upgrade it.
    const controlKey=keys(),controlPair=await (await json('/devices/pair/start',{name:'Isolated control PC',os:'Windows',agentVersion:'test',publicKey:controlKey.publicKey,capabilities:['commands','files']})).json();
    assert.deepEqual(controlPair.capabilities,['read','control','commands','files']);
