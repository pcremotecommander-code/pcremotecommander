    for(let i=0;i<20&&staleSocket.readyState===1;i++)await pause(100);
    assert.notEqual(staleSocket.readyState,1,'A fresh signed connection should replace the stale socket');
    // Obtain an actual gateway OAuth token through consent + upstream identity + PKCE.
    const registered=await (await json('/register',{client_name:'PC Commander runtime test',redirect_uris:['https://client.example/callback'],grant_types:['authorization_code','refresh_token'],response_types:['code'],token_endpoint_auth_method:'none'})).json();
